def emit_patterns():
    """docs/assets/patterns.data.js — the library's text catalogue, as data.

    The showcase used to describe the library in prose while the library sat
    in files nobody browsing the site would ever open. This ships the actual
    file contents, so the page cannot show a pattern the repository does not
    have, and adding a .txt file puts it on the site."""
    mods = []
    for name, note in PATTERN_MODULES:
        d = ROOT / "library" / name
        if not d.exists():
            continue
        order = PATTERN_ORDER.get(name, [])
        rank = lambda f: (order.index(f.stem) if f.stem in order else len(order), f.stem)
        files = []
        for f in sorted(d.glob("*.txt"), key=rank):
            text = f.read_text().rstrip()
            # the first comment line is the file's own one-line description
            head = ""
            for line in text.splitlines():
                if line.startswith("#") and len(line) > 2:
                    head = line.lstrip("# ").strip()
                    break
            files.append({"name": f.stem, "note": head, "body": text})
        mods.append({"key": name, "note": note, "files": files})
    body = json.dumps({"modules": mods}, ensure_ascii=False, indent=1)
    w(DOCS / "patterns.data.js",
      "/* yoshiki — generated by tools/build.py from library/*.txt. Do not edit.\n"
      " * The catalogue page renders these; adding a .txt file adds a pattern. */\n"
      "window.YOSHIKI_PATTERNS = " + body + ";\n")


