def load(slug: str) -> dict:
    return yaml.safe_load((PAL / slug / "palette.yml").read_text())


def resolve(raw: dict, parent: dict | None) -> dict:
    out = {"meta": raw["meta"], "semantic": raw.get("semantic", {}), "notes": raw.get("notes", {})}
    tokens = dict(parent["tokens"]) if parent else {}
    tokens.update(raw.get("tokens", {}))
    out["tokens"] = tokens

    term = dict(parent["terminal"]) if parent else {}
    t = dict(raw.get("terminal", {}))
    if t.pop("inherit-exact", None) and parent:   # washi: dark island, copy as-is
        out["terminal"] = dict(parent["terminal"])
    else:
        ansi = list(t.pop("ansi", term.get("ansi", [])))
        brights = list(t.pop("brights", term.get("brights", [])))
        if "ansi-black" in t:
            ansi[0] = t.pop("ansi-black")
        if "brights-black" in t:
            brights[0] = t.pop("brights-black")
        term.update(t)
        term["ansi"], term["brights"] = ansi, brights
        out["terminal"] = term

    b24 = dict(parent["base24"]) if parent else {}
    b24.update(raw.get("base24", {}))
    out["base24"] = b24

    roles = dict(parent["roles"]) if parent else {}
    roles.update(raw.get("roles", {}))
    for new, old in ROLE_ALIASES.items():     # v2 contract names, resolved from the v1 roles
        if old in roles:
            roles.setdefault(new, roles[old])
    out["roles"] = roles

    # groups describe the tokens as scales; a variant inherits the parent's map
    out["groups"] = raw.get("groups") or (parent["groups"] if parent else [])
    out["brand"] = raw.get("brand") or (parent["brand"] if parent else {})
    return out


def role_var(spec: str):
    """Resolve a role spec to a CSS value that points AT the token variable —
    `--r-text-body: var(--bone-1)`. A theme then overrides tokens only."""
    name, _, op = spec.partition("@")
    ref = f"var(--{name.strip()})"
    if op:
        return f"color-mix(in srgb, {ref} {op.strip().rstrip('%')}%, transparent)"
    return ref


def role_value(spec: str, tok: dict):
    """Resolve a role spec ('token' or 'token @NN') to (css_value, base_hex)."""
    name, _, op = spec.partition("@")
    base = tok.get(name.strip(), name.strip())
    if op:
        return f"color-mix(in srgb, {base} {op.strip().rstrip('%')}%, transparent)", base
    return base, base


# WCAG relative luminance / contrast — proof the foundation holds
def _lum(h):
    h = h.lstrip("#")
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4 for x in c]
    return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]


def contrast(a, b):
    la, lb = sorted((_lum(a), _lum(b)), reverse=True)
    return round((la + .05) / (lb + .05), 2)


def w(path: Path, text: str):
    rel = path.relative_to(ROOT)
    if CHECK:
        if not path.exists() or path.read_text() != text:
            drift.append(str(rel))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"  {rel}")


def emit(slug: str, p: dict):
    d = PAL / slug
    name = p["meta"]["name"]
    head = f"yoshiki {name} v{p['meta']['version']} — generated by tools/build.py; edit palette.yml instead"
    tok, term = p["tokens"], p["terminal"]

    # json — resolved machine-readable bundle (tokens + resolved roles)
    roles_for_json = {r: role_value(spec, p["tokens"])[0] for r, spec in p["roles"].items()}
    w(d / f"{slug}.json", json.dumps({**p, "roles_resolved": roles_for_json},
                                      ensure_ascii=False, indent=2) + "\n")

    # dtcg — W3C Design Tokens (agent / Style-Dictionary readable): tokens grouped by
    # prefix under `color`, roles as aliases under `role` (or a mix value for @NN).
    def dtcg_ref(name):
        g, sep, m = name.partition("-")
        return f"{{color.{g}.{m}}}" if sep else f"{{color.{name}}}"
    color_tree: dict = {}
    for k, v in tok.items():
        g, sep, m = k.partition("-")
        if sep:
            color_tree.setdefault(g, {})[m] = {"$value": v, "$type": "color"}
        else:
            color_tree[k] = {"$value": v, "$type": "color"}
    role_tree = {}
    for r, spec in p["roles"].items():
        nm, _, op = spec.partition("@")
        val = role_value(spec, tok)[0] if op else dtcg_ref(nm.strip())
        role_tree[r.replace(".", "-")] = {"$value": val, "$type": "color"}
    dtcg = {"$description": f"yoshiki {slug} — W3C DTCG design tokens (generated)",
            "color": color_tree, "role": role_tree}
    w(d / f"{slug}.tokens.json", json.dumps(dtcg, ensure_ascii=False, indent=2) + "\n")

    # roles resolved to css values (the consumer-facing contract)
    roles = {r: role_value(spec, tok)[0] for r, spec in p["roles"].items()}

    # css variables — raw tokens + semantic role aliases (--r-<role>)
    css = [f"/* {head} */", ":root{", "  /* tokens */"]
    css += [f"  --{k}: {v};" for k, v in tok.items()]
    css.append("  /* semantic roles — prefer these */")
    css += [f"  --r-{r.replace('.', '-')}: {v};" for r, v in roles.items()]
    css.append("}")
    w(d / f"{slug}.css", "\n".join(css) + "\n")


def check_groups(resolved: dict) -> list[str]:
    """Every token must sit in exactly one group — the group map is what the
    docs render, so a token missing from it is a token nobody can find."""
    problems = []
    for slug, pal in resolved.items():
        listed, seen = [], set()
        for g in pal["groups"]:
            for st in g["steps"]:
                t = st["token"]
                if t in seen:
                    problems.append(f"{slug}: token {t} listed in more than one group")
                seen.add(t)
                if t in pal["tokens"]:
                    listed.append(t)
                elif not st.get("optional"):
                    problems.append(f"{slug}: group {g['key']} names unknown token {t}")
        for t in pal["tokens"]:
            if t not in seen:
                problems.append(f"{slug}: token {t} belongs to no group")
    return problems


def emit_site_palette(resolved: dict):
    """docs/assets/palette.css — the showcase wears the canon itself.

    Roles point at token variables (`--r-text-body: var(--bone-1)`), so a theme
    overrides tokens and the whole role layer follows. The site therefore has no
    palette of its own to drift from."""
    base = resolved[DARK]
    v = base["meta"]["version"]
    out = [f"/* yoshiki v{v} — generated by tools/build.py from canon/palettes. Do not edit.",
           " * Tokens are raw values; roles are the contract — consume --r-* in the site.",
           " * A theme overrides tokens only; every role follows through var(). */",
           # both selectors, so a nested block can force EITHER theme — a page
           # that shows the two side by side needs the parent theme overridable
           f':root, [data-theme="{base["meta"]["slug"]}"]{{',
           f"  color-scheme: {base['meta']['mode']};",
           f"  /* tokens — {base['meta']['name']} */"]
    out += [f"  --{k}: {val};" for k, val in base["tokens"].items()]
    out.append("  /* roles — the consumer-facing contract */")
    out += [f"  --r-{r.replace('.', '-')}: {role_var(spec)};" for r, spec in base["roles"].items()]
    out.append("}")

    for slug in ORDER:
        if slug == DARK:
            continue
        var = resolved[slug]
        diff = {k: val for k, val in var["tokens"].items() if base["tokens"].get(k) != val}
        out += [f'[data-theme="{var["meta"]["slug"]}"]{{',
                f"  color-scheme: {var['meta']['mode']};",
                f"  /* tokens that differ from the default — {var['meta']['name']} */"]
        out += [f"  --{k}: {val};" for k, val in diff.items()]
        # Every role is repeated here, not just the ones washi remaps. A custom
        # property is substituted where it is DECLARED, so a child inherits the
        # value the parent already resolved: an element carrying data-theme="washi"
        # inside a kogane page would take paper tokens and the dark theme's
        # already-computed roles. Re-declaring the whole contract is what makes a
        # nested scope — two themes shown side by side — actually work.
        out.append("  /* the whole contract again, so a nested scope resolves it here */")
        out += [f"  --r-{r.replace('.', '-')}: {role_var(spec)};" for r, spec in var["roles"].items()]
        out.append("}")
    css = "\n".join(out) + "\n"
    # the shipped artifact, and the copy the site is served from (docs/ is the
    # Pages root, so it cannot reach up into library/ — the mirror is checked)
    w(WEB / "palette.css", css)
    w(DOCS / "palette.css", css)


def emit_site_data(resolved: dict, proof: dict):
    """docs/assets/palette.data.js — the same canon, as data the pages read.

    Token values, the group map with each step's job, the roles contract, the
    ANSI ramp and the generated contrast proof. The showcase renders this; it
    never carries a hex of its own."""
    themes = {}
    for slug, pal in resolved.items():
        themes[slug] = {
            "meta": pal["meta"],
            "tokens": pal["tokens"],
            "roles": {r: role_value(spec, pal["tokens"])[0] for r, spec in pal["roles"].items()},
            "roleTokens": pal["roles"],
            "terminal": pal["terminal"],
            "base24": pal["base24"],
            "proof": proof[slug],
        }
    data = {
        "version": resolved[ORDER[0]]["meta"]["version"],
        "order": ORDER,
        "groups": resolved[ORDER[0]]["groups"],
        "themes": themes,
        "ansiNames": ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"],
    }
    body = json.dumps(data, ensure_ascii=False, indent=1)
    w(DOCS / "palette.data.js",
      "/* yoshiki — generated by tools/build.py from canon/palettes. Do not edit.\n"
      " * The showcase reads this; it holds no palette of its own. */\n"
      "window.YOSHIKI = " + body + ";\n")


PROMPT_START = "# ── tokens, generated from canon/palettes/night-beige/palette.yml ──"
PROMPT_END = "# ── end tokens ──"


def emit_palette_prompt(pal: dict):
    """canon/prompts/palette.md ships the tokens inline, so a model can be given
    the palette in one paste. A hand-copied token block is a hand-copied token
    block: it went stale the first time a value moved. The build owns it now."""
    import textwrap
    tok = pal["tokens"]
    lines = [PROMPT_START]
    for g in pal["groups"]:
        steps = [s for s in g["steps"] if s["token"] in tok]
        if not steps:
            continue
        body = " · ".join(f"{s['token']} {tok[s['token']]} ({s['job']})" for s in steps)
        head = g["label"].upper()
        wrapped = textwrap.wrap(body, width=74 - len(head) - 2,
                                subsequent_indent="  ", break_long_words=False)
        lines.append(f"{head}  {wrapped[0]}")
        lines += wrapped[1:]
    lines.append(PROMPT_END)
    block = "\n".join(lines)

    f = ROOT / "canon" / "prompts" / "palette.md"
    cur = f.read_text()
    a, b = cur.index(PROMPT_START), cur.index(PROMPT_END) + len(PROMPT_END)
    w(f, cur[:a] + block + cur[b:])


# ── the mark ────────────────────────────────────────────────────────────
# One character on a lacquer tile, set in the display serif. The character is
# declared in canon/palettes/kogane/palette.yml under `brand.mark`, so changing
# the identity is a one-line edit rather than a redraw — and so the guard in
# tools/check.py can tell the one deliberate mark apart from decoration.
MARK_SERIF = "'Shippori Mincho','Noto Serif JP','Hiragino Mincho ProN','Yu Mincho',serif"


def mark_svg(tok: dict, glyph: str, size: int = 32, rounded: bool = True,
             live: bool = False) -> str:
    if live:
        tok = {k: f"var(--{k})" for k in ("ink-0", "ink-1", "line-0", "kin-1")}
    r = 8 if rounded else 0
    # a latin mark sits on its baseline; a CJK one is centred on its em box
    wide = any(ord(c) > 0x2E7F for c in glyph)
    fs, y = (21, 23.4) if wide else (19, 22.6)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="{size}" '
        f'height="{size}" role="img" aria-label="yoshiki">'
        f'<rect width="32" height="32" rx="{r}" fill="{tok["ink-1"]}"/>'
        f'<text x="16" y="{y}" text-anchor="middle" font-family="{MARK_SERIF}" '
        f'font-size="{fs}" font-weight="700" fill="{tok["kin-1"]}">{glyph}</text>'
        f'<rect x=".5" y=".5" width="31" height="31" rx="{max(0, r - 0.5)}" fill="none" '
        f'stroke="{tok["line-0"]}"/></svg>'
    )


def emit_mark(resolved: dict):
    tok = resolved[DARK]["tokens"]
    glyph = resolved[DARK]["brand"]["mark"]
