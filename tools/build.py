# ── the contract the proof enforces ──────────────────────────────────────
# Text is measured against EVERY surface it can sit on — bg.hover included,
# which on paper is the darkest ground of all. A role that passes only on its
# favourite background is not proven, it is flattered.
SURFACES = ["bg.app", "bg.surface", "bg.raised", "bg.hover"]
TEXT_ROLES = [
    ("text.heading", 4.5), ("text.body", 4.5), ("text.secondary", 4.5),
    ("text.muted", 4.5), ("text.ghost", 3.0), ("text.gold", 4.5),
    ("text.link", 4.5), ("text.gold-dim", 4.5), ("action.text", 4.5), ("ok.text", 4.5),
    ("warn.text", 4.5), ("danger.text", 4.5), ("info.text", 4.5),
    ("special.text", 4.5),
]
# gilding is an edge, not a word: 3:1 is the non-text floor (WCAG 1.4.11)
EDGE_ROLES = [("border.gold", 3.0), ("action.edge", 3.0), ("action.hover.edge", 3.0)]
# syntax renders on the theme's own page (the editor follows the theme; only the
# integrated terminal stays a dark island)
SYNTAX_ROLES = [("syntax.keyword", 4.5), ("syntax.string", 4.5), ("syntax.number", 4.5),
                ("syntax.type", 4.5), ("syntax.constant", 4.5), ("syntax.comment", 3.0)]
# a wash is the tinted field its own text sits in; a fill is the trigger itself,
# and the label standing on it is the easiest contrast to forget
WASH_PAIRS = [("ok.text", "ok.wash", 4.5), ("danger.text", "danger.wash", 4.5),
              ("ok.on-fill", "ok.fill", 4.5), ("danger.on-fill", "danger.fill", 4.5)]
ANSI_FLOOR = 4.5   # every foreground colour over the terminal background


def measure(pal: dict) -> dict:
    """Every claim the palette makes, checked. Returns the proof as data."""
    tok = pal["tokens"]

    def hexof(role):
        return role_value(pal["roles"][role], tok)[1]

    def cell(fg, bg, floor):
        r = contrast(fg, bg)
        return {"ratio": r, "floor": floor, "pass": r >= floor}

    surf = {s: hexof(s) for s in SURFACES}
    proof = {"surfaces": surf, "matrix": [], "syntax": [], "edges": [], "wash": [], "ansi": []}
    for role, floor in TEXT_ROLES:
        fg = hexof(role)
        proof["matrix"].append({"role": role, "hex": fg, "floor": floor,
                                "cells": {s: cell(fg, b, floor) for s, b in surf.items()}})
    for role, floor in EDGE_ROLES:
        fg = hexof(role)
        proof["edges"].append({"role": role, "hex": fg, "floor": floor,
                               "cells": {s: cell(fg, b, floor) for s, b in surf.items()}})
    app = surf["bg.app"]
    for role, floor in SYNTAX_ROLES:
        fg = hexof(role)
        proof["syntax"].append({"role": role, "hex": fg, "on": "bg.app", **cell(fg, app, floor)})
    for fg_r, bg_r, floor in WASH_PAIRS:
        fg, bg = hexof(fg_r), hexof(bg_r)
        proof["wash"].append({"role": fg_r, "on": bg_r, "hex": fg, "bg": bg, **cell(fg, bg, floor)})
    term_bg = pal["terminal"]["background"]
    for i, c in enumerate(pal["terminal"]["ansi"][1:] + pal["terminal"]["brights"][1:], start=1):
        name = ["red", "green", "yellow", "blue", "magenta", "cyan", "white"][(i - 1) % 7]
        kind = "ansi" if i <= 7 else "bright"
        proof["ansi"].append({"role": f"{kind}.{name}", "hex": c, "on": "terminal.background",
                              "bg": term_bg, **cell(c, term_bg, ANSI_FLOOR)})
    return proof


def failures(proof: dict) -> list[str]:
    out = []
    for block in ("matrix", "edges"):
        for row in proof[block]:
            for s, c in row["cells"].items():
                if not c["pass"]:
                    out.append(f"{row['role']} on {s}: {c['ratio']}:1 < {c['floor']}")
    for block in ("syntax", "wash", "ansi"):
        for row in proof[block]:
            if not row["pass"]:
                out.append(f"{row['role']} on {row['on']}: {row['ratio']}:1 < {row['floor']}")
    return out


def write_contrast(resolved: dict, proofs: dict) -> bool:
    def mark(c):
        return f"{c['ratio']}" if c["pass"] else f"**{c['ratio']} ✗**"

    doc = ["# Contrast — WCAG proof\n",
           "Auto-generated by `tools/build.py`; the build fails if a single cell drops",
           "below its floor. Text is measured against **every** surface it can sit on,",
           "not just the flattering one — on paper `bg.hover` is the darkest ground, so",
           "that column is the real test. Gilding is measured at the 3:1 non-text floor",
           "(WCAG 1.4.11): a gold edge is an edge, not a word.\n"]
    bad_all = []
    for slug, pal in resolved.items():
        pr, bad = proofs[slug], failures(proofs[slug])
        bad_all += [f"{slug}: {b}" for b in bad]
        doc.append(f"## {pal['meta']['name']} ({pal['meta']['mode']})\n")
        head = "| role | " + " | ".join(s.split(".")[1] for s in SURFACES) + " | floor |"
        rule = "|---|" + "---|" * (len(SURFACES) + 1)
        doc += ["### Text on every surface\n", head, rule]
        for row in pr["matrix"]:
            cells = " | ".join(mark(row["cells"][s]) for s in SURFACES)
            doc.append(f"| `{row['role']}` | {cells} | {row['floor']} |")
        doc += ["", "### Gilding — an edge, floor 3:1\n", head, rule]
        for row in pr["edges"]:
            cells = " | ".join(mark(row["cells"][s]) for s in SURFACES)
            doc.append(f"| `{row['role']}` | {cells} | {row['floor']} |")
        doc += ["", "### Syntax on the editor page · washes · terminal ANSI\n",
                "| role | on | ratio | floor | |", "|---|---|---|---|---|"]
        for row in pr["syntax"] + pr["wash"] + pr["ansi"]:
            doc.append(f"| `{row['role']}` | `{row['on']}` | {row['ratio']}:1 | "
                       f"{row['floor']} | {'✓' if row['pass'] else '✗ FAIL'} |")
        doc.append("")
    doc.insert(6, f"**Status: {'every role passes on every surface.' if not bad_all else 'FAILURES PRESENT.'}**\n")
    w(PAL / "CONTRAST.md", "\n".join(doc))
    for b in bad_all:
        print(f"contrast: {b}")
    return not bad_all


